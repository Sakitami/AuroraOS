#!/usr/bin/env python3
"""Builds the Game Boy app (GameBoy.bin, in the current folder unless -o).

1. The ARM11 job: arm11/job.c11 (Peanut-GB and minigb_apu's registers),
   compiled for the ARM11 as cpu-stress builds its job, linked at GB11_CODE
   and turned into build/gb11_blob.h.
2. The app, with the SDK (../sdk/aurcc.py): main.c, sound.c and core.c;
   main.c finds the blob and runs the emulation on the ARM11 with it.

`py sdk/aurcc.py build gameboy` still works without step 1: main.c then has
no blob and runs the emulation on the ARM9.

Run from anywhere: py gameboy/build.py [-o APP.bin] [-v]
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
BUILD = HERE / "build"
CC = "arm-none-eabi-gcc"
OBJCOPY = "arm-none-eabi-objcopy"
CODE_MAX = 0x40000  # GB11_CODE_MAX in arm11/gb11.h

ARM11 = ["-march=armv6k", "-mtune=mpcore", "-mfloat-abi=hard", "-marm"]
CFLAGS = ARM11 + ["-O2", "-mword-relocations", "-ffunction-sections",
                  "-fdata-sections", "-fno-tree-loop-distribute-patterns",
                  "-ffreestanding", "-fno-builtin", "-mno-unaligned-access",
                  "-Wall", "-Wextra", "-I", str(HERE / "arm11")]


def run(cmd, verbose):
    if verbose:
        print("  $ " + " ".join(str(c) for c in cmd))
    r = subprocess.run([str(c) for c in cmd])
    if r.returncode:
        sys.exit(r.returncode)


def blob_header(data: bytes) -> str:
    lines = ["/* Generated by build.py from arm11/job.c11. */",
             f"#define GB11_SIZE {len(data)}u",
             "static const unsigned char gb11_blob[] = {"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
                     + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description="Build the Game Boy app.")
    p.add_argument("-o", "--output", default="GameBoy.bin")
    p.add_argument("-v", "--verbose", action="store_true")
    a = p.parse_args()

    if not shutil.which(CC):
        sys.exit(f"{CC} was not found on PATH (devkitARM)")
    BUILD.mkdir(exist_ok=True)
    obj = BUILD / "job11.o"
    run([CC, *CFLAGS, "-x", "c", "-c", HERE / "arm11" / "job.c11", "-o", obj],
        a.verbose)
    elf = BUILD / "job11.elf"
    run([CC, *ARM11, "-T", HERE / "arm11" / "job11.ld", "-nostdlib",
         "-nostartfiles", "-Wl,--build-id=none", "-Wl,--gc-sections",
         "-Wl,--no-warn-rwx-segments",
         obj, "-lgcc", "-o", elf], a.verbose)
    bin_path = BUILD / "job11.bin"
    run([OBJCOPY, "-O", "binary", elf, bin_path], a.verbose)
    data = bin_path.read_bytes()
    if len(data) > CODE_MAX:
        sys.exit("the ARM11 job is larger than GB11_CODE_MAX")
    (BUILD / "gb11_blob.h").write_text(blob_header(data), encoding="ascii",
                                       newline="\n")
    print(f"ARM11 job: {len(data)} bytes")

    run([sys.executable, REPO / "sdk" / "aurcc.py", "build",
         HERE / "main.c", HERE / "sound.c", HERE / "core.c", "-I", BUILD,
         "--icon", HERE / "GameBoy.icon", "-o", a.output,
         *(["-v"] if a.verbose else [])], a.verbose)


if __name__ == "__main__":
    main()
